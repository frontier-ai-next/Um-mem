func TestLegacyPythonHarmEventVetoesWithoutSQLiteCredit(t *testing.T) {
	root := t.TempDir()
	path, err := Path(root, "alpha")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
		t.Fatal(err)
	}
	// Generated by Python append_supervisor_ledger_event/hash_value with fixed
	// event identity and timestamp; legacy events have no credit_subject.
	const line = `{"event_id": "ledger-legacyharm", "ts": 1.5, "workspace_id": "alpha", "actor": "verifier", "stage_id": "memory_application", "tool": "memory_application_verification", "result": {"verifier_id": "legacy-verifier", "decision_id": "decision-harm", "action_trace_id": "trace-harm", "memory_id": "procedure-1", "usage_event_id": "usage-harm", "task_signature": "task-signature", "outcome": "hurt", "passed": true}, "result_hash": "766f59929a552e9698d05d42c76deb406326d860ecdfa126d949e3def07e015c", "event_hash": "b62e901ccdf80732d4893647ce3223875851d0033e9165b60e7ea4d9a9f34d81"}`
	if err := os.WriteFile(path, []byte(line+"\n"), 0600); err != nil {
		t.Fatal(err)
	}
	resolver, err := OpenResolver(root, "alpha")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature", nil); err == nil {
		t.Fatal("Python legacy harm event was ignored after its SQLite credit was removed")
	}
}

func applicationCredit(t *testing.T, root, creditID, decisionID, traceID,
	usageID, domain, outcome string) memory.OutcomeCreditEvent {
	t.Helper()
	basis := "deterministic_verifier"
	if outcome == "hurt" {
		basis = "proven_regression"
	}
	credit := memory.OutcomeCreditEvent{CreditID: creditID, DecisionID: decisionID,
		WorkspaceID: "alpha", TaskSignature: "task-signature", ActionTraceID: traceID,
		MemoryIDs: []string{"procedure-1"}, AppliedUsageEventIDs: []string{usageID},
		Outcome: outcome, AttributionBasis: basis, VerifierResult: "passed",
		TaskFamily: "implementation", Stage: "test", ProjectID: "project-1",
		HostID: "host-1", ProfileID: "team", IndependenceDomain: domain,
		EvidenceRefs: []memory.EvidenceRef{{RefType: "test_run", RefID: "test-" + creditID,
			ProducedBy: "verifier", ProducerID: "verifier-1"}},
		Reason: "observed application", CreatedAt: "2026-10-24T12:00:00Z"}
	proof, err := AppendMemoryApplicationVerification(ApplicationVerificationRequest{
		RepoRoot: root, VerifierID: "verifier-1", Credit: credit,
		MemoryID: "procedure-1", UsageEventID: usageID, Passed: true})
	if err != nil {
		t.Fatal(err)
	}
	credit.EvidenceRefs = append(credit.EvidenceRefs, proof)
	return credit
}

func TestProcedureGateRejectsRehashedSQLiteDomainRewrite(t *testing.T) {
	root := t.TempDir()
	indexPath := filepath.Join(root, "index.sqlite")
	if err := store.CreateIndex(indexPath); err != nil {
		t.Fatal(err)
	}
	first := applicationCredit(t, root, "credit-1", "decision-1", "trace-1", "usage-1", "same-domain", "helped")
	second := applicationCredit(t, root, "credit-2", "decision-2", "trace-2", "usage-2", "same-domain", "helped")
	second.IndependenceDomain = "forged-other-domain"
	db, err := sql.Open("sqlite", indexPath)
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	for _, credit := range []memory.OutcomeCreditEvent{first, second} {
		payload, err := jsoncompat.MarshalPython(credit, false)
		if err != nil {
			t.Fatal(err)
		}
		hash := sha256.Sum256(payload)
		envelope, err := json.Marshal(map[string]any{"payload": credit,
			"payload_sha256": hex.EncodeToString(hash[:])})
		if err != nil {
			t.Fatal(err)
		}
		if _, err := db.Exec(`INSERT INTO usage(block_id,workspace_id,outcome,payload_json)
			VALUES(?,?,?,?)`, "outcome-credit-event:"+credit.CreditID, "alpha", "outcome_credit",
			string(envelope)); err != nil {
			t.Fatal(err)
		}
	}
	index, err := store.OpenIndex(indexPath, "alpha", "team")
	if err != nil {
		t.Fatal(err)
	}
	defer index.Close()
	credits, err := index.OutcomeCreditsForMemory(context.Background(), "procedure-1")
	if err != nil || len(credits) != 2 {
		t.Fatalf("rewritten SQLite credit did not reach proof gate: %v, %v", len(credits), err)
	}
	resolver, err := OpenResolver(root, "alpha")
	if err != nil {
		t.Fatal(err)
	}
	gate, err := resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature", credits)
	if err != nil || gate.Allowed || len(gate.VerifiedOutcomeIDs) != 1 {
		t.Fatalf("rehashed SQLite domain rewrite forged independent proof: %+v, %v", gate, err)
	}
	_ = applicationCredit(t, root, "credit-harm", "decision-harm", "trace-harm",
		"usage-harm", "domain-harm", "hurt")
	resolver, err = OpenResolver(root, "alpha")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature", credits); err == nil {
		t.Fatal("deleted SQLite harm credit hid its host verifier event")
	}
}

func TestVerifiedProcedurePromotionGateRequiresIndependentLedgerApplications(t *testing.T) {
	root := t.TempDir()
	first := applicationCredit(t, root, "credit-1", "decision-1", "trace-1", "usage-1", "domain-1", "helped")
	second := applicationCredit(t, root, "credit-2", "decision-2", "trace-2", "usage-2", "domain-2", "helped")
	resolver, err := OpenResolver(root, "alpha")
	if err != nil {
		t.Fatal(err)
	}
	gate, err := resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature",
		[]memory.OutcomeCreditEvent{first, second})
	if err != nil || !gate.Allowed || len(gate.VerifiedOutcomeIDs) != 2 ||
		gate.Reason != "independent_verified_outcomes_satisfied" {
		t.Fatalf("two independent verified applications were rejected: %+v, %v", gate, err)
	}
	duplicateDomain := second
	duplicateDomain.IndependenceDomain = "domain-1"
	gate, err = resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature",
		[]memory.OutcomeCreditEvent{first, duplicateDomain})
	if err != nil || gate.Allowed || len(gate.VerifiedOutcomeIDs) != 1 {
		t.Fatalf("duplicate independence domain was counted: %+v, %v", gate, err)
	}
	forgedDomain := second
	forgedDomain.IndependenceDomain = "forged-independent-domain"
	gate, err = resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature",
		[]memory.OutcomeCreditEvent{first, forgedDomain})
	if err != nil || gate.Allowed {
		t.Fatalf("unverified independence domain was counted: %+v, %v", gate, err)
	}
	forged := second
	forged.EvidenceRefs = append([]memory.EvidenceRef(nil), second.EvidenceRefs...)
	badHash := "forged"
	forged.EvidenceRefs[len(forged.EvidenceRefs)-1].Hash = &badHash
	gate, err = resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature",
		[]memory.OutcomeCreditEvent{first, forged})
	if err != nil || gate.Allowed {
		t.Fatalf("forged application proof was counted: %+v, %v", gate, err)
	}
	multi := second
	multi.CreditID, multi.DecisionID, multi.ActionTraceID = "credit-multi", "decision-multi", "trace-multi"
	multi.MemoryIDs = []string{"procedure-1", "other-memory"}
	multi.AppliedUsageEventIDs = []string{"usage-multi"}
	multi.IndependenceDomain = "domain-multi"
	multi.EvidenceRefs = []memory.EvidenceRef{{RefType: "test_run", RefID: "test-multi",
		ProducedBy: "verifier", ProducerID: "verifier-1"}}
	multiProof, err := AppendMemoryApplicationVerification(ApplicationVerificationRequest{
		RepoRoot: root, VerifierID: "verifier-1", Credit: multi,
		MemoryID: "procedure-1", UsageEventID: "usage-multi", Passed: true})
	if err != nil {
		t.Fatal(err)
	}
	multi.EvidenceRefs = append(multi.EvidenceRefs, multiProof)
	forgedSingle := multi
	forgedSingle.MemoryIDs = []string{"procedure-1"}
	resolver, err = OpenResolver(root, "alpha")
	if err != nil {
		t.Fatal(err)
	}
	gate, err = resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature",
		[]memory.OutcomeCreditEvent{first, forgedSingle})
	if err != nil || gate.Allowed {
		t.Fatalf("multi-memory outcome was forged into single-memory support: %+v, %v", gate, err)
	}
	hurt := applicationCredit(t, root, "credit-3", "decision-3", "trace-3", "usage-3", "domain-3", "hurt")
	resolver, err = OpenResolver(root, "alpha")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature",
		[]memory.OutcomeCreditEvent{first, second, hurt}); err == nil {
		t.Fatal("verified harmful application did not block procedure promotion")
	}
	hiddenHarm := hurt
	hiddenHarm.Outcome = "neutral"
	hiddenHarm.AttributionBasis = "insufficient_linkage"
	hiddenHarm.MemoryIDs = nil
	if _, err := resolver.VerifiedProcedurePromotionGate("procedure-1", "team", "task-signature",
		[]memory.OutcomeCreditEvent{first, second, hiddenHarm}); err == nil {
		t.Fatal("rewritten neutral credit hid verified harmful application")
	}
}
